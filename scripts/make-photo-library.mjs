/**
 * Generates lib/blog/photo-library.ts.
 *
 * A blog post written in the admin panel stores its cover as a filename, not
 * as a module — a database row cannot hold a static import. But every image on
 * this site is served through next/image with `placeholder="blur"`, and a blur
 * placeholder is computed at build time from the file itself. A plain string
 * src gets no placeholder at all.
 *
 * So the covers live in a generated module of static imports and the database
 * stores the key. The post keeps its blur, its intrinsic size and its
 * build-time optimisation, and Dani still only has to pick a photo.
 *
 * Only files tracked by git are listed. There are 26 raw shoot photos sitting
 * untracked in public/images; a static import of one of those would build fine
 * here and fail on Vercel, where the file does not exist.
 *
 *   node scripts/make-photo-library.mjs
 */
import { execFileSync } from "child_process";
import { writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Not photographs: logos, icons, favicons. */
const EXCLUDE = /^(favicon|logo|icon|apple-)/i;

const tracked = execFileSync("git", ["ls-files", "public/images"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .map((l) => l.slice("public/images/".length))
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .filter((f) => !EXCLUDE.test(f))
  .sort();

if (!tracked.length) throw new Error("no tracked images found under public/images");

/** `blog-places.jpg` -> `blogPlaces`. A valid identifier for the import. */
const ident = (f) =>
  f
    .replace(/\.(jpe?g|png)$/i, "")
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^[0-9]/, (d) => `p${d}`);

/** `guide-beach-club.jpg` -> `Guide beach club`. Shown in the picker. */
const label = (f) => {
  const base = f.replace(/\.(jpe?g|png)$/i, "").replace(/[-_]+/g, " ");
  return base.charAt(0).toUpperCase() + base.slice(1);
};

const lines = [];
lines.push("/* GENERATED by scripts/make-photo-library.mjs — do not edit by hand.");
lines.push(" * Run `npm run blog:photos` after adding a photo to public/images.");
lines.push(" *");
lines.push(" * Static imports, so every cover keeps its build-time blur placeholder and");
lines.push(" * intrinsic size even though the post that uses it lives in the database.");
lines.push(" */");
lines.push('import type { StaticImageData } from "next/image";');
for (const f of tracked) lines.push(`import ${ident(f)} from "@/public/images/${f}";`);
lines.push("");
lines.push("export const PHOTO_LIBRARY = {");
for (const f of tracked) lines.push(`  "${f}": ${ident(f)},`);
lines.push("} as const satisfies Record<string, StaticImageData>;");
lines.push("");
lines.push("export type PhotoKey = keyof typeof PHOTO_LIBRARY;");
lines.push("");
lines.push("/** Every photo, for the cover picker. */");
lines.push("export const PHOTO_CHOICES: { key: PhotoKey; label: string; image: StaticImageData }[] = [");
for (const f of tracked) lines.push(`  { key: "${f}", label: "${label(f)}", image: ${ident(f)} },`);
lines.push("];");
lines.push("");
lines.push("/** The cover a post falls back to if its stored key no longer exists. */");
lines.push(`export const DEFAULT_COVER: PhotoKey = "${tracked.includes("blog-hero.jpg") ? "blog-hero.jpg" : tracked[0]}";`);
lines.push("");
lines.push("export function resolveCover(key: string | null | undefined): StaticImageData {");
lines.push("  if (key && key in PHOTO_LIBRARY) return PHOTO_LIBRARY[key as PhotoKey];");
lines.push("  return PHOTO_LIBRARY[DEFAULT_COVER];");
lines.push("}");
lines.push("");

const out = path.join(root, "lib/blog/photo-library.ts");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`wrote lib/blog/photo-library.ts — ${tracked.length} photos`);
